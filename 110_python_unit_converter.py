# Unit Converter - 10 practical features

# 1. Kilometers to miles
print("1. 10 km to miles:", 10 * 0.621371)

# 2. Miles to kilometers
print("2. 5 miles to km:", 5 * 1.60934)

# 3. Celsius to Fahrenheit
print("3. 30 C to F:", (30 * 9 / 5) + 32)

# 4. Fahrenheit to Celsius
print("4. 86 F to C:", (86 - 32) * 5 / 9)

# 5. Kilograms to pounds
print("5. 10 kg to pounds:", 10 * 2.20462)

# 6. Pounds to kilograms
print("6. 22 pounds to kg:", 22 * 0.453592)

# 7. Meters to feet
print("7. 5 m to feet:", 5 * 3.28084)

# 8. Feet to meters
print("8. 16 feet to m:", 16 * 0.3048)

# 9. Liters to gallons
print("9. 10 liters to gallons:", 10 * 0.264172)

# 10. Inches to centimeters
print("10. 10 inches to cm:", 10 * 2.54)
